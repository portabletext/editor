import {readdirSync, readFileSync} from 'node:fs'
import {join, relative} from 'node:path'

export type Surface = 'docs' | 'readme' | 'jsdoc'

export type Fence = {
  surface: Surface
  /** Repo-relative path of the file the fence was found in. */
  source: string
  /** 1-based line of the first line of code inside the fence. */
  line: number
  language: ExampleLanguage
  skipped: boolean
  continues: boolean
  code: string
}

type ExampleLanguage = 'ts' | 'tsx' | 'js' | 'jsx'

/**
 * Fence meta word that opts an example out of the check. Expressive Code
 * parses a bare meta word as a boolean option no plugin reads, and GitHub and
 * npm ignore everything after the language, so readers never see it.
 */
export const optOutMarker = 'nocheck'

/**
 * Fence meta word that checks an example as one program together with the
 * nearest earlier checked example in the same file, for snippets that build on
 * an earlier one. Invisible to readers for the same reasons as
 * {@link optOutMarker}.
 */
export const continuationMarker = 'continue'

const languages: Record<string, ExampleLanguage> = {
  ts: 'ts',
  typescript: 'ts',
  tsx: 'tsx',
  js: 'js',
  jsx: 'jsx',
}

export function collectFences(repoRoot: string): Array<Fence> {
  const docsRoot = join(repoRoot, 'apps/docs/src/content/docs')
  const packagesRoot = join(repoRoot, 'packages')
  const fences: Array<Fence> = []

  for (const file of walk(docsRoot)) {
    if (relative(docsRoot, file).split('/')[0] === 'api') {
      // Generated by typedoc from the JSDoc covered below.
      continue
    }
    if (/\.mdx?$/.test(file)) {
      fences.push(...markdownFences(repoRoot, file, 'docs'))
    }
  }

  for (const packageName of readdirSync(packagesRoot).sort()) {
    const readme = join(packagesRoot, packageName, 'README.md')
    try {
      fences.push(...markdownFences(repoRoot, readme, 'readme'))
    } catch {
      continue
    }
  }

  for (const packageName of readdirSync(packagesRoot).sort()) {
    for (const file of walk(join(packagesRoot, packageName, 'src'))) {
      if (/\.tsx?$/.test(file) && !/\.test\.tsx?$/.test(file)) {
        fences.push(...jsdocFences(repoRoot, file))
      }
    }
  }

  return fences
}

function markdownFences(
  repoRoot: string,
  file: string,
  surface: Surface,
): Array<Fence> {
  const lines = readFileSync(file, 'utf8').split('\n')
  return fencesInLines(lines).map((fence) => ({
    surface,
    source: relative(repoRoot, file),
    line: fence.lineIndex + 1,
    language: fence.language,
    skipped: fence.skipped,
    continues: fence.continues,
    code: fence.code,
  }))
}

/**
 * Only fences inside an `@example` tag count: other fenced blocks in JSDoc
 * are prose illustrations, not examples a consumer copies.
 */
function jsdocFences(repoRoot: string, file: string): Array<Fence> {
  const text = readFileSync(file, 'utf8')
  const fences: Array<Fence> = []

  for (const comment of text.matchAll(/\/\*\*[\s\S]*?\*\//g)) {
    const startLineIndex = text.slice(0, comment.index).split('\n').length - 1
    const commentLines = comment[0]
      .split('\n')
      .map((line) =>
        line.replace(/^\s*\/?\*\*?\/?\s?/, '').replace(/\*\/$/, ''),
      )

    let inExample = false
    let exampleLines: Array<string> = []
    let exampleStart = 0
    const flush = () => {
      for (const fence of fencesInLines(exampleLines)) {
        fences.push({
          surface: 'jsdoc',
          source: relative(repoRoot, file),
          line: startLineIndex + exampleStart + fence.lineIndex + 1,
          language: fence.language,
          skipped: fence.skipped,
          continues: fence.continues,
          code: fence.code,
        })
      }
      exampleLines = []
    }

    commentLines.forEach((line, index) => {
      const tag = /^@(\w+)/.exec(line.trim())
      if (tag && !insideFence(exampleLines)) {
        if (inExample) {
          flush()
        }
        inExample = tag[1] === 'example'
        exampleStart = index + 1
        return
      }
      if (inExample) {
        exampleLines.push(line)
      }
    })
    if (inExample) {
      flush()
    }
  }

  return fences
}

type RawFence = {
  /** 0-based index of the first code line within the scanned lines. */
  lineIndex: number
  language: ExampleLanguage
  skipped: boolean
  continues: boolean
  code: string
}

function fencesInLines(lines: Array<string>): Array<RawFence> {
  const fences: Array<RawFence> = []
  let index = 0

  while (index < lines.length) {
    const opening = /^(\s*)(`{3,}|~{3,})(.*)$/.exec(lines[index] ?? '')
    if (!opening) {
      index++
      continue
    }
    const [, indent = '', marker = '', info = ''] = opening
    const closing = new RegExp(`^\\s*${marker[0]}{${marker.length},}\\s*$`)
    const start = index + 1
    let end = start
    while (end < lines.length && !closing.test(lines[end] ?? '')) {
      end++
    }

    const [tag = '', ...meta] = info.trim().split(/\s+/)
    const language = languages[tag]
    if (language) {
      fences.push({
        lineIndex: start,
        language,
        skipped: meta.includes(optOutMarker),
        continues: meta.includes(continuationMarker),
        code: lines
          .slice(start, end)
          .map((line) =>
            line.startsWith(indent) ? line.slice(indent.length) : line,
          )
          .join('\n'),
      })
    }
    index = end + 1
  }

  return fences
}

function insideFence(lines: Array<string>): boolean {
  return lines.filter((line) => /^\s*(`{3,}|~{3,})/.test(line)).length % 2 === 1
}

function* walk(directory: string): Generator<string> {
  let entries
  try {
    entries = readdirSync(directory, {withFileTypes: true})
  } catch {
    return
  }
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) {
      if (entry.name !== 'node_modules') {
        yield* walk(path)
      }
    } else {
      yield path
    }
  }
}
